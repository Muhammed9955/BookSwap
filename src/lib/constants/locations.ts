/**
 * Returns available districts for a given governorate string.
 * Supports partial matching (e.g. 'Cairo' or 'القاهرة').
 */
export function getDistrictsForGovernorate(governorate: string): string[] {
  if (!governorate) return []
  
  // Direct key lookup
  if (EGYPT_DISTRICTS[governorate]) {
    return EGYPT_DISTRICTS[governorate]
  }

  // Partial match lookup
  const normalized = governorate.toLowerCase()
  for (const [key, districts] of Object.entries(EGYPT_DISTRICTS)) {
    if (
      (normalized.includes('cairo') || normalized.includes('قاهر')) && key.includes('Cairo') ||
      (normalized.includes('giza') || normalized.includes('جيز')) && key.includes('Giza') ||
      (normalized.includes('alex') || normalized.includes('إسكندر')) && key.includes('Alexandria') ||
      (normalized.includes('mansoura') || normalized.includes('دقهل')) && key.includes('Mansoura') ||
      (normalized.includes('tanta') || normalized.includes('غرب')) && key.includes('Tanta') ||
      (normalized.includes('zagazig') || normalized.includes('شرق')) && key.includes('Zagazig') ||
      (normalized.includes('port said') || normalized.includes('بورسعيد')) && key.includes('Port Said')
    ) {
      return districts
    }
  }

  return []
}

/**
 * Returns top 6-8 popular districts for quick chip clicks.
 */
export function getTopDistricts(governorate: string, limit = 8): string[] {
  const all = getDistrictsForGovernorate(governorate)
  return all.slice(0, limit)
}
